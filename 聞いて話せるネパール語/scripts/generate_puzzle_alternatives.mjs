// Reviewed, single-clause exercises allow the time phrase before the subject.
// Other clauses and coordinated sentences need their own reviewed ordering.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const app = fileURLToPath(new URL('../', import.meta.url));
const expo = path.join(app, 'expo-app');
const read = name => JSON.parse(fs.readFileSync(path.join(expo, name), 'utf8'));
const examples = Object.values(read('data/ota-baseline/core.json').examplesNe).flat();
const lessons = Object.values(read('data/overlays/ja.json').learningPathV3.exercises);
const alternatives = new Map();
for (const {ne} of lessons) {
  const m = /^(म|हामी|उहाँ|तपाईं) (आज|भोलि) (\S+ \S+।)$/u.exec(ne);
  if (m) alternatives.set(ne, [m[2], m[1], m[3]].join(' '));
}
for (const [model, answer] of [
  ['म सात बजे उठ्छु।', 'सात बजे म उठ्छु।'],
  ['मलाई स्याउ मन पर्छ।', 'स्याउ मलाई मन पर्छ।'],
  ['मलाई तरकारी मन पर्छ।', 'तरकारी मलाई मन पर्छ।'],
  ['मलाई खेलकुद मन पर्छ।', 'खेलकुद मलाई मन पर्छ।'],
  ['मलाई खाना पकाउन मन पर्छ।', 'खाना पकाउन मलाई मन पर्छ।'],
  ['मलाई नेपाली संस्कृतिमा धेरै रुचि छ।', 'नेपाली संस्कृतिमा मलाई धेरै रुचि छ।'],
  ['तपाईंलाई माछा मन पर्छ?', 'माछा तपाईंलाई मन पर्छ?'],
  ['सप्ताहन्तमा साथीहरूसँग फुटबल खेल्न मलाई मन पर्छ।', 'मलाई सप्ताहन्तमा साथीहरूसँग फुटबल खेल्न मन पर्छ।'],
]) {
  if (!examples.includes(model)) throw Error('Missing model: ' + model);
  alternatives.set(model, answer);
}

const config = {...process.env};
for (const envFile of [path.join(app, '../聞いて話せる日本語/.env'), path.join(app, '.env')]) {
  if (!fs.existsSync(envFile)) continue;
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*(AZURE_SPEECH_KEY|AZURE_SPEECH_REGION)\s*=\s*(.*?)\s*$/);
    if (m) config[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const dir = path.join(expo, 'assets/puzzle-audio');
const lines = [];
for (const [model, ne] of alternatives) {
  const name = createHash('sha256').update(ne).digest('hex').slice(0, 16) + '.mp3';
  const file = path.join(dir, name);
  if (!fs.existsSync(file)) {
    const region = config.AZURE_SPEECH_REGION;
    if (!/^[a-z0-9]+$/.test(region ?? '') || !config.AZURE_SPEECH_KEY) throw Error('Missing Azure Speech configuration');
    const response = await fetch('https://' + region + '.tts.speech.microsoft.com/cognitiveservices/v1', {
      method: 'POST',
      headers: {'Ocp-Apim-Subscription-Key': config.AZURE_SPEECH_KEY, 'Content-Type': 'application/ssml+xml', 'X-Microsoft-OutputFormat': 'audio-24khz-48kbitrate-mono-mp3'},
      body: '<speak version="1.0" xml:lang="ne-NP"><voice name="ne-NP-HemkalaNeural"><prosody rate="0%">' + ne.replaceAll('&','&amp;').replaceAll('<','&lt;') + '</prosody></voice></speak>',
    });
    if (!response.ok) throw Error('Azure Speech HTTP ' + response.status);
    const bytes = Buffer.from(await response.arrayBuffer());
    if (bytes.length < 600 || !response.headers.get('content-type')?.includes('audio')) throw Error('Invalid audio for ' + ne);
    fs.mkdirSync(dir, {recursive: true});
    fs.writeFileSync(file, bytes);
    await new Promise(resolve => setTimeout(resolve, 3000)); // Free-tier request pacing
  }
  lines.push('  ' + JSON.stringify(model) + ': { ne: ' + JSON.stringify(ne) + ', audio: require(' + JSON.stringify('../../assets/puzzle-audio/' + name) + ') },');
}
fs.writeFileSync(path.join(expo, 'src/pack/puzzleAlternatives.ts'), '// Generated by generate_puzzle_alternatives.mjs. Keyed by the complete model sentence.\nexport const puzzleAlternatives = {\n' + lines.join('\n') + '\n};\n');
console.log(alternatives.size + ' reviewed alternatives with audio.');
